#!/usr/bin/env bash
# Generate a deterministic ~500 KB Markdown document with 100+ code blocks
# in mixed languages, plus tables, lists, headings, and inline formatting.
# No randomness; running it twice produces identical bytes.

set -euo pipefail

OUTPUT_DIR="${1:-.build/bench}"
mkdir -p "$OUTPUT_DIR"
OUTPUT_FILE="$OUTPUT_DIR/fixture.md"

# Use a temp file and replace atomically so a partial write doesn't corrupt
# an existing fixture.
TEMP_FILE=$(mktemp)
trap "rm -f $TEMP_FILE" EXIT

# Saved so the closing status line below can reach the terminal instead of
# the fixture: `exec >` redirects stdout for the rest of this shell, and
# after `mv` moves $TEMP_FILE to $OUTPUT_FILE, fd 1 is still the same open
# file — now reachable at the new path — so anything written after the move
# without restoring fd 1 first lands inside the "finished" fixture.
exec 3>&1
exec > "$TEMP_FILE"

# Header and introduction.
cat << 'EOF'
# Benchmark Fixture

A deterministic large document for measuring latency. Generated by `make-bench-fixture.sh`.

This document contains 100+ fenced code blocks in various languages, plus tables, lists,
headings, and inline formatting, all designed to exercise the rendering pipeline.

## Overview

The document is organized into sections, each demonstrating different Markdown features
that a real document might contain. Code blocks are the primary cost driver, as they
trigger highlight.js for syntax highlighting.

## Table of Contents

- [Code Blocks](#code-blocks)
- [Lists](#lists)
- [Tables](#tables)
- [Inline Formatting](#inline-formatting)

---

## Code Blocks

This section contains 100+ fenced code blocks in different languages.

EOF

# Generate code blocks in various languages. Each block is large enough to
# exercise the renderer but not so large that a single block dominates.
# We cycle through languages to create variety.

LANGUAGES=(
  "swift"
  "python"
  "javascript"
  "java"
  "go"
  "rust"
  "c"
  "bash"
  "sql"
  "html"
  "css"
  "json"
  "yaml"
  "markdown"
  "xml"
)

# Generate code blocks. We want 100+, so let's make 120 blocks.
for i in {1..120}; do
  LANG_IDX=$((i % ${#LANGUAGES[@]}))
  LANG="${LANGUAGES[$LANG_IDX]}"

  cat << EOF

### Code Block $i ($LANG)

\`\`\`$LANG
// Example code block in $LANG
// This is line 2 of the code block
// This is line 3 of the code block
// This is line 4 of the code block
// This is line 5 of the code block
function example$i() {
  const variable1 = "value1";
  const variable2 = "value2";
  const variable3 = "value3";
  const variable4 = "value4";
  const variable5 = "value5";
  return {
    result: variable1,
    data: variable2,
    status: variable3,
    code: variable4,
    message: variable5
  };
}
\`\`\`

Example $i demonstrates the $LANG language. This is a sentence about the code.
This is another sentence to pad the content. This helps exercise the rendering.

EOF
done

